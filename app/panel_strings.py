def words(lang: str) -> dict[str, str]:
    """One flat lookup for the interface, already resolved to this language.

    The carried-context labels come from lang.CARRIED rather than being copied
    here. They appear in two places — the answer's "carried over from your last
    question" line and the User Interaction row in the panel — and two copies
    of the same eight translations would drift apart the first time one was
    edited.
    """
    from . import lang as lang_mod

    out = {k: v.get(lang) or v["en"] for k, v in WORDS.items()}
    for key, pack in lang_mod.CARRIED.items():
        out.setdefault(key, pack.get(lang) or pack["en"])
    return out
